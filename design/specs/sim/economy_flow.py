#!/usr/bin/env python3
"""
economy_flow.py — источники и стоки по неделям для каждого сегмента (MONETIZATION_PLAN §2).
Единица сравнения — «желание-эквивалент» (ж.э.) = 150 кр. Данные дохода — GDD v11 §5.3–5.4; платящие — профили §1 плана.
Запуск: python3 economy_flow.py
Всё, что не из GDD, помечено [ГИП] в плане и меняется параметрами ниже.
"""
GEM_PER_WISH = 150
SEASON_WEEKS = 8

# --- бесплатные источники за устоявшуюся неделю (после дня 14), в кр / билетах / монетах / лепестках ---
FREE = {
    "F2P лёгкий":   dict(gems=50*7*0.5 + 25*7*0.5 + 50, tickets=5.0, coins=450, petals=60,  pass_gems=2000*0.45/SEASON_WEEKS, event_tix=4/SEASON_WEEKS),
    "F2P активный": dict(gems=172*7 + 370,              tickets=7.0, coins=1100, petals=150, pass_gems=2000*0.95/SEASON_WEEKS, event_tix=12/SEASON_WEEKS),
}
# платящие — те же бесплатные источники, что у активного (рационально: платящий играет не меньше)
FREE["Малый платящий (минноу)"] = FREE["F2P активный"]
FREE["Дельфин"] = FREE["F2P активный"]
FREE["Кит"] = FREE["F2P активный"]
FREE["Кракен"] = FREE["F2P активный"]

# --- платные расходы ₽ в неделю: (категория -> ₽) [ГИП]; 1 месяц = 4.33 недели ---
PAID_RUB_MONTH = {
    "F2P лёгкий":   {},
    "F2P активный": {},
    "Малый платящий (минноу)": {"Нефритовый пропуск": 199*0.85, "пакет камня 79–199": 0},
    "Дельфин":      {"Лунный пропуск": 449, "дорожка премиум (1 раз в 2 мес)": 899/2, "пакеты камня": 150, "прямые S/★/оттенки": 150},
    "Кит":          {"Лунный пропуск": 449, "дорожка Люкс (1 раз в 2 мес)": 1990/2, "прямой SSR+ каждый сезон": 2490/1.87,
                     "пакеты камня": 2400, "★/оттенки/рамки/декор": 1100},
    "Кракен":       {"Лунный пропуск": 449, "дорожка Люкс": 1990/2, "прямые наряды (бэклог+новые)": 14000, "пакеты камня": 17000,
                     "★/оттенки/декор/реквизит/фонды": 7500},
}
# доля платных ₽, превращаемая в камень (желания) — остальное в прямые покупки/косметику
MOON_SHARE = {"Малый платящий (минноу)": 1.0, "Дельфин": 0.55, "Кит": 0.45, "Кракен": 0.50}
RUB_PER_WISH = 37.4

def card_wishes(seg):
    # карточки: Нефритовый 199 ₽ = 150 камня сразу + 25 кр/сут × 30 = 900 кр (6 желаний, 33.2 ₽/ж); Лунный 449 ₽ = 300 + 60×30 = 2100 кр (14 желаний, 32.1 ₽/ж)
    r = PAID_RUB_MONTH[seg]
    w = 0.0
    if "Нефритовый пропуск" in r: w += (900) / GEM_PER_WISH / 4.33 * (r["Нефритовый пропуск"] / 199)
    if "Лунный пропуск" in r:    w += (2100) / GEM_PER_WISH / 4.33
    return w

def main():
    print("| Сегмент | Бесп. ж.э./нед | Платн. ж.э./нед | Всего ж.э./нед | ж.э./сезон (8 нед) | ₽/мес (модель) | ₽ на 1 ж.э. (платных) |")
    print("|---|---|---|---|---|---|---|")
    for seg, f in FREE.items():
        free_w = (f["gems"] + f["pass_gems"]) / GEM_PER_WISH + f["tickets"] + f["event_tix"]
        rub_m = sum(PAID_RUB_MONTH[seg].values())
        rub_w = rub_m / 4.33
        cards = card_wishes(seg)
        share = MOON_SHARE.get(seg, 0)
        moon_w = 0.0
        if seg in MOON_SHARE:
            pack_rub_w = rub_w * share
            # карточки уже учтены в cards; остаток (пакеты) по 37.4 ₽
            card_rub_w = (PAID_RUB_MONTH[seg].get("Нефритовый пропуск", 0) + PAID_RUB_MONTH[seg].get("Лунный пропуск", 0)) / 4.33
            moon_w = cards + max(0.0, pack_rub_w - card_rub_w) / RUB_PER_WISH
        tot = free_w + moon_w
        ppw = (rub_w * share / moon_w) if moon_w else 0
        print(f"| {seg} | {free_w:.1f} | {moon_w:.1f} | {tot:.1f} | {tot*SEASON_WEEKS:.0f} | {rub_m:,.0f} | {ppw:.1f} |".replace(",", " "))

    print()
    print("Недельные источники/стоки по валютам, активный F2P (устоявшаяся неделя):")
    f = FREE["F2P активный"]
    print(f"  кр: источники ≈ {f['gems']+f['pass_gems']:.0f}  (задания/режимы {f['gems']:.0f} + дорожка {f['pass_gems']:.0f});  билеты: {f['tickets']+f['event_tix']:.1f}")
    print(f"  монеты: ≈ {f['coins']}; лепестки: ≈ {f['petals']}")

if __name__ == "__main__":
    main()
