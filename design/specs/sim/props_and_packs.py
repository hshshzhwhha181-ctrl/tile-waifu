#!/usr/bin/env python3
"""
props_and_packs.py — таблица пакетов камня (₽/желание), первая покупка ×2, стоимость «Шкатулки» (реквизит), ценность наборов (value ratio).
Запуск: python3 props_and_packs.py
"""
from gacha_exact import PROPS, featured_dist, stats

PACKS = [  # ₽, камень (кратно 150), первая покупка ×2 (только 79/199/499/990)
    (79, 300, True), (199, 750, True), (499, 1950, True), (990, 3900, True),
    (1990, 7950, False), (2990, 12000, False),
    (4990, 20100, False), (9990, 40350, False), (14990, 60750, False),
]
print("| ₽ | камень | желаний | ₽/желание | первая покупка ×2: камень / желаний / ₽/желание |")
print("|---|---|---|---|---|")
for rub, moon, x2 in PACKS:
    w = moon / 150
    s = f"{moon*2:,} / {w*2:.0f} / {rub/(w*2):.1f}".replace(",", " ") if x2 else "—"
    print(f"| {rub:,} | {moon:,} | {w:.0f} | {rub/w:.1f} | {s} |".replace(",", " "))

print()
pm = featured_dist(PROPS); st = stats(pm)
rub_per_prop_wish = 100 / 150 * 37.4
print(f"«Шкатулка»: среднее желаний до избранного реквизита {st['mean']:.1f}; медиана {st['q'][0.5]}; p90 {st['q'][0.9]}; макс {st['max']}")
print(f"  цена желания 100 кр ≈ {rub_per_prop_wish:.1f} ₽ (по пакету 2 990) → среднее ≈ {st['mean']*rub_per_prop_wish:,.0f} ₽; p90 ≈ {st['q'][0.9]*rub_per_prop_wish:,.0f} ₽; худший ≈ {st['max']*rub_per_prop_wish:,.0f} ₽".replace(",", " "))

print()
print("Ценность наборов: value ratio = (сумма прайс-листа содержимого ₽) / (цена набора ₽). Прайс-лист — §4 плана.")
BUNDLES = [
    # name, price, list of (item, list_price)
    ("Набор сезона «Витрина» (SSR+ + 3 S + ★2–★5 SSR+ + оттенок + дорожка премиум)", 5390,
        [("SSR+", 2490), ("3×S", 1797), ("★2–★5 SSR+", 666), ("dye_3", 199), ("дорожка премиум", 899)]),
    ("Набор героини «Гардероб» (SSR + S + ★2–★5 + оттенок)", 2490,
        [("SSR", 1490), ("S", 599), ("★2–★5 SSR", 446), ("dye_3", 199)]),
    ("Фонд Пути (7 500 кр по аркам Пути)", 990, [("7 500 кр = 50 желаний ≈ 1 870 ₽ (по 37.4)", 1870)]),
    ("Фонд Коллекции (6 вех)", 1490, [("9 000 кр = 60 жел ≈ 2 244 ₽", 2244), ("рамка+титул", 298)]),
    ("Вечеринка-пропуск (косметика события)", 299, [("рамка", 149), ("эффект", 99), ("тайл-сет", 199)]),
]
print("| Набор | цена ₽ | прайс-лист ₽ | value ratio |")
print("|---|---|---|---|")
for n, price, items in BUNDLES:
    lp = sum(p for _, p in items)
    print(f"| {n} | {price:,} | {lp:,} | {lp/price:.2f} |".replace(",", " "))
