#!/usr/bin/env python3
"""
whale_curve.py — «кривая кита»: что можно купить на X ₽ за 12 месяцев и где кончается каталог (MONETIZATION_PLAN §5, §9).
Каталог = SKIN_HUD_SYSTEM §6.2/6.5 (38 платных скинов за 12 мес: 27 S, 6 SSR, 5 SSR+) + позиции §4 плана.
Все цены — прейскурант плана (§4). Покупка «напрямую» (без желаний) — верхняя оценка потолка коллекционера.
Запуск: python3 whale_curve.py
"""
CATALOG = [
    # (категория, шт., цена ₽, приоритет кита: меньше = покупает раньше)
    ("Дорожка «Люкс» (6 сезонов)",                   6, 1990, 1),
    ("SSR+ напрямую (5 шт.)",                        5, 2490, 2),
    ("SSR напрямую (6 шт.)",                         6, 1490, 3),
    ("Звёзды ★2–★5 на SSR+ (5×666)",                 5,  666, 4),
    ("Звёзды ★2–★5 на SSR (6×446)",                  6,  446, 5),
    ("Режиссёрская ульта (SSR/SSR+ 11 шт.)",        11,  590, 6),
    ("Реквизит ульты «Шкатулка» напрямую (11)",     11, 1090, 7),
    ("Оттенок dye_3 (SSR/SSR+ 11 шт.)",             11,  199, 8),
    ("S напрямую (27 шт.)",                         27,  599, 9),
    ("Люкс-будуар героини (комната Салона, 10)",    10, 1290, 10),
    ("Декор сезона (6)",                             6,  490, 11),
    ("Звёзды ★2–★5 на S (27×446)",                  27,  446, 12),
    ("Вечеринка-пропуск (18 событий)",              18,  299, 13),
    ("Рамки/титулы/эффекты лобби (40 × 149)",       40,  149, 14),
    ("Лавка стола (сукно/тайлы/эффекты, 6 сезонов)", 6,  449, 15),
    ("Фонд Пути + Фонд Коллекции",                   1, 2480, 16),
    ("Позы для фото-режима (10 героинь × 199)",     10,  199, 17),
    ("Лунный пропуск 12 мес",                       12,  449, 18),
    ("«Пасьянс+»",                                   1,  399, 19),
]
def total():
    return sum(n * p for _, n, p, _ in CATALOG)

if __name__ == "__main__":
    T = total()
    print(f"Потолок коллекционера за 12 мес (всё напрямую, без единого желания): {T:,} ₽".replace(",", " "))
    print()
    print("| Категория | шт. | цена | сумма ₽ | доля потолка |")
    print("|---|---|---|---|---|")
    for name, n, p, _ in sorted(CATALOG, key=lambda x: x[3]):
        print(f"| {name} | {n} | {p:,} | {n*p:,} | {n*p/T*100:.1f}% |".replace(",", " "))
    print(f"| **Итого** | | | **{T:,}** | 100% |".replace(",", " "))
    print()
    print("Жадная покупка по приоритету кита: что закрыто на бюджете B (шт. из N):")
    budgets = [3000, 6000, 12000, 25000, 50000, 75000, 100000, 125000, 150000]
    order = sorted(CATALOG, key=lambda x: x[3])
    print("| Бюджет ₽ | потрачено | закрыто позиций из " + str(sum(n for _, n, _, _ in CATALOG)) + " | покрытие потолка | что закрыто полностью |")
    print("|---|---|---|---|---|")
    for B in budgets:
        left = B; bought = 0; spent = 0; full = []
        for name, n, p, _ in order:
            k = min(n, left // p)
            left -= k * p; spent += k * p; bought += k
            if k == n: full.append(name.split(" (")[0])
        print(f"| {B:,} | {spent:,} | {bought} | {spent/T*100:.0f}% | {', '.join(full[:6])}{'…' if len(full)>6 else ''} |".replace(",", " "))
    print()
    # по месяцам: «текущий поток нового контента» после запуска
    launch = 12*599 + 4*1490 + 2*2490       # S + SSR + SSR+ запуска
    per_season = 1*2490*0.4 + 1*1490*0.3 + 3*599  # усредн. 6 сезонов: 5 SSR+ и 6 SSR всего, из них часть на запуске
    print(f"Запуск (прямой прайс 12 S + 4 SSR + 2 SSR+): {launch:,} ₽ + ★/оттенки/декор — «бэклог», который кит выкупает в 1–3 мес.".replace(",", " "))
    steady = (T - (launch + 6*0)) / 12
    print(f"Средний поток после бэклога (грубо): {(T - launch) / 12:,.0f} ₽/мес всего каталога минус запуск — это потолок «кита», а не «кракена».".replace(",", " "))
