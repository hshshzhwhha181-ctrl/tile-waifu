#!/usr/bin/env python3
"""gen_tokens.py - generate TWTokens (GDScript constants) and the TW Godot Theme from tokens.json (P27 / WP9a).

  game/shell/design/tokens.json   single source of the "Tishina i lak" style (hex colours, 8-pt spacing, hit targets,
                                  radii, elevation, motion, closed type scale). One key per line, sorted: additive-only edits.
  game/shell/design/tw_tokens.gd  GENERATED  class_name TWTokens - typed consts + a few static helpers
  game/shell/design/tw_theme.tres GENERATED  Theme resource built from the same tokens (text .tres, no Godot needed)

  python3 tools/gen_tokens.py            # (re)write both outputs; also re-sorts/normalises tokens.json
  python3 tools/gen_tokens.py --check    # exit 1 if outputs on disk differ from what tokens.json produces (CI gate)

Deterministic: no timestamps, sorted keys, fixed float formatting. Hex literals appear ONLY in tokens.json and in the
generated tw_tokens.gd (lint_tokens.py whitelists exactly those files).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DESIGN = REPO / "game" / "shell" / "design"
TOKENS = DESIGN / "tokens.json"
OUT_GD = DESIGN / "tw_tokens.gd"
OUT_THEME = DESIGN / "tw_theme.tres"

HEX_RE = re.compile(r"^#[0-9A-Fa-f]{6}$")
NAME_RE = re.compile(r"^[A-Z][A-Z0-9_]*$")
TRANS = {"LINEAR", "SINE", "QUINT", "QUART", "QUAD", "EXPO", "ELASTIC", "CUBIC", "CIRC", "BOUNCE", "BACK", "SPRING"}
EASE = {"IN", "OUT", "IN_OUT", "OUT_IN"}


def fnum(v) -> str:
    """Stable number formatting for GDScript / tres."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    s = repr(round(float(v), 6))
    return s


def load(path: Path = TOKENS) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def dump_tokens(tok: dict) -> str:
    return json.dumps(tok, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def validate(tok: dict) -> list[str]:
    errs: list[str] = []
    for k, v in tok.get("color", {}).items():
        if not NAME_RE.match(k) or not HEX_RE.match(v):
            errs.append(f"color.{k}={v!r}: need UPPER_SNAKE name and #RRGGBB")
    for h, d in tok.get("heroes", {}).items():
        for f in ("accent", "glow", "deep"):
            if not HEX_RE.match(d.get(f, "")):
                errs.append(f"heroes.{h}.{f}: bad hex")
    sc = tok["type"]["scale"]
    if sorted(sc.values(), reverse=True) != [64, 44, 34, 30, 26]:
        errs.append(f"type.scale must be exactly 64/44/34/30/26 (closed scale), got {sorted(sc.values(), reverse=True)}")
    if tok["type"]["TYPE_SUBTITLE"] != 36:
        errs.append("type.TYPE_SUBTITLE must be 36")
    if tok["hit"]["HIT_TARGET_MIN"] != 96 or tok["hit"]["HIT_TARGET_BIG"] != 112:
        errs.append("hit: HIT_TARGET_MIN must be 96 and HIT_TARGET_BIG 112 (GDD 7.2)")
    g = tok["space"]["GRID"]
    for k, v in tok["space"].items():
        if k not in ("HALF", "GRID") and v % g:
            errs.append(f"space.{k}={v} is not a multiple of GRID={g}")
    for name, e in tok["motion"]["ease"].items():
        if e["trans"] not in TRANS or e["ease"] not in EASE:
            errs.append(f"motion.ease.{name}: unknown trans/ease")
    names: dict[str, str] = {}
    for sec in ("color", "alpha", "space", "hit", "radius"):
        for k in tok[sec]:
            if k in names:
                errs.append(f"duplicate const {k} in {sec} and {names[k]}")
            names[k] = sec
    return errs


# ---------------------------------------------------------------- GDScript
def gd_color(h: str) -> str:
    return f'Color("{h.upper()}")'


def build_gd(tok: dict) -> str:
    L: list[str] = []
    a = L.append
    a("# GENERATED by tools/gen_tokens.py from tokens.json - DO NOT EDIT (edit tokens.json, re-run the generator).")
    a("# TWTokens: single source of the 'Tishina i lak' style. Hex literals live only here and in tokens.json.")
    a("class_name TWTokens")
    a("extends RefCounted")
    a("")
    a(f"const BASE_WIDTH: int = {tok['_meta']['base_width']}")
    a("")
    a("# --- colour ---")
    for k in sorted(tok["color"]):
        a(f"const {k}: Color = {gd_color(tok['color'][k])}")
    a("")
    a("# --- alpha ---")
    for k in sorted(tok["alpha"]):
        a(f"const {k}: float = {fnum(tok['alpha'][k])}")
    a("")
    a("# --- spacing (8-pt grid, base 720) ---")
    for k in sorted(tok["space"], key=lambda x: (tok["space"][x], x)):
        a(f"const {k}: int = {fnum(tok['space'][k])}")
    a("")
    a("# --- hit targets (GDD 7.2) ---")
    for k in sorted(tok["hit"]):
        a(f"const {k}: int = {fnum(tok['hit'][k])}")
    a("")
    a("# --- radii ---")
    for k in sorted(tok["radius"], key=lambda x: (tok["radius"][x], x)):
        a(f"const {k}: int = {fnum(tok['radius'][k])}")
    a("")
    a("# --- elevation (shadow blur px, y offset px, alpha) ---")
    for k in sorted(tok["elevation"]):
        e = tok["elevation"][k]
        a(f'const {k}: Dictionary = {{"alpha": {fnum(e["alpha"])}, "blur": {fnum(e["blur"])}, "dy": {fnum(e["dy"])}}}')
    a("")
    a("# --- motion: durations (s) ---")
    for k in sorted(tok["motion"]["dur"]):
        a(f"const {k}: float = {fnum(tok['motion']['dur'][k])}")
    a("# --- motion: easings (feed Tween.set_trans / set_ease) ---")
    for k in sorted(tok["motion"]["ease"]):
        e = tok["motion"]["ease"][k]
        a(f'const {k}: Dictionary = {{"ease": Tween.EASE_{e["ease"]}, "trans": Tween.TRANS_{e["trans"]}}}')
    a("")
    a("# --- type scale (closed; base 720, scaled by text-size setting 100/125/150 %) ---")
    for k in sorted(tok["type"]["scale"], key=lambda x: (-tok["type"]["scale"][x], x)):
        a(f"const {k}: int = {fnum(tok['type']['scale'][k])}")
    a(f"const TYPE_SUBTITLE: int = {fnum(tok['type']['TYPE_SUBTITLE'])}")
    sizes = sorted(tok["type"]["scale"].values(), reverse=True)
    a(f"const TYPE_SIZES: Array[int] = [{', '.join(str(s) for s in sizes)}]")
    a(f"const TEXT_SCALE_STEPS: Array[float] = [{', '.join(fnum(s) for s in tok['type']['text_scale_steps'])}]")
    a("")
    a("# --- layout metrics ---")
    for k in sorted(tok["layout"]):
        v = tok["layout"][k]
        if isinstance(v, dict):
            a(f"const {k}: Dictionary = {{{', '.join(chr(34)+kk+chr(34)+': '+fnum(vv) for kk, vv in sorted(v.items()))}}}")
        else:
            a(f"const {k}: int = {fnum(v)}")
    a("")
    a("# --- heroine accents (accent / glow / deep) ---")
    a("const HEROES: Dictionary = {")
    hs = sorted(tok["heroes"])
    for i, h in enumerate(hs):
        d = tok["heroes"][h]
        comma = "," if i < len(hs) - 1 else ""
        a(f'\t"{h}": {{"accent": {gd_color(d["accent"])}, "deep": {gd_color(d["deep"])}, "element": "{d["element"]}", '
          f'"glow": {gd_color(d["glow"])}, "name": "{d["name"]}"}}{comma}')
    a("}")
    a("")
    a("")
    a("static func hero(id: String) -> Dictionary:")
    a('\treturn HEROES.get(id, HEROES["mc"])')
    a("")
    a("")
    a("static func hair() -> Color:")
    a("\treturn Color(GOLD_700, HAIR_A)")
    a("")
    a("")
    a("static func snap(v: float) -> float:")
    a("\treturn roundf(v / GRID) * GRID")
    a("")
    a("")
    a("static func font(base: int, text_scale: float = 1.0) -> int:")
    a("\t# only closed-scale sizes (plus subtitle) are legal; text_scale is the 100/125/150 % user setting")
    a("\tassert(base in TYPE_SIZES or base == TYPE_SUBTITLE, \"font size %d is not on the TW type scale\" % base)")
    a("\treturn int(roundf(base * text_scale))")
    a("")
    a("")
    a("static func hit(big: bool = false) -> int:")
    a("\treturn HIT_TARGET_BIG if big else HIT_TARGET_MIN")
    a("")
    a("")
    a("static func tween_ease(t: Tween, ease_token: Dictionary) -> Tween:")
    a("\treturn t.set_trans(ease_token[\"trans\"]).set_ease(ease_token[\"ease\"])")
    a("")
    return "\n".join(L)


# ---------------------------------------------------------------- Theme (.tres)
def rgba(h: str, alpha: float = 1.0) -> str:
    h = h.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
    return f"Color({fnum(round(r, 5))}, {fnum(round(g, 5))}, {fnum(round(b, 5))}, {fnum(alpha)})"


def build_theme(tok: dict) -> str:
    c = tok["color"]
    al = tok["alpha"]
    rad = tok["radius"]
    sp = tok["space"]
    ty = tok["type"]["scale"]
    subs: list[tuple[str, list[str]]] = []

    def box(sid: str, bg: str, bg_a: float = 1.0, border: str | None = None, border_a: float = 1.0, border_w: int = 0,
            radius: int | None = None, pad_x: int = 0, pad_y: int = 0, shadow: bool = False) -> None:
        p = [f"bg_color = {rgba(c[bg], bg_a)}"]
        if border:
            p.append(f"border_color = {rgba(c[border], border_a)}")
            p.append(f"border_width_left = {border_w}")
            p.append(f"border_width_top = {border_w}")
            p.append(f"border_width_right = {border_w}")
            p.append(f"border_width_bottom = {border_w}")
        r = rad["R_XS"] if radius is None else radius
        p += [f"corner_radius_top_left = {r}", f"corner_radius_top_right = {r}",
              f"corner_radius_bottom_right = {r}", f"corner_radius_bottom_left = {r}"]
        p += [f"content_margin_left = {pad_x}", f"content_margin_top = {pad_y}",
              f"content_margin_right = {pad_x}", f"content_margin_bottom = {pad_y}"]
        if shadow:
            e = tok["elevation"]["E2"]
            p += [f"shadow_color = {rgba(c['NIGHT_900'], e['alpha'])}", f"shadow_size = {e['blur'] // 2}",
                  f"shadow_offset = Vector2(0, {e['dy']})"]
        subs.append((sid, p))

    px, py = sp["S3"], sp["S2"]
    box("sb_plate", "NIGHT_800", al["ON_ART_A"], "GOLD_700", al["HAIR_A"], 1, rad["R_SM"], px, py)
    box("sb_sheet", "NIGHT_700", 1.0, "GOLD_700", al["HAIR_A"], 1, rad["R_MD"], px, py, shadow=True)
    box("sb_btn", "NIGHT_700", 1.0, "GOLD_700", al["HAIR_A"], 1, rad["R_SM"], px, py)
    box("sb_btn_hover", "NIGHT_600", 1.0, "GOLD_500", 1.0, 1, rad["R_SM"], px, py)
    box("sb_btn_pressed", "NIGHT_600", 1.0, "GOLD_300", 1.0, 2, rad["R_SM"], px, py)
    box("sb_btn_disabled", "NIGHT_800", 0.6, "GOLD_700", al["HAIR_A"] * 0.5, 1, rad["R_SM"], px, py)
    box("sb_focus", "NIGHT_900", 0.0, "GOLD_500", 1.0, 2, rad["R_SM"], px, py)
    box("sb_primary", "ROSE_500", 1.0, "ROSE_300", 1.0, 1, rad["R_SM"], px, py)
    box("sb_primary_hover", "ROSE_300", 1.0, "GOLD_300", 1.0, 1, rad["R_SM"], px, py)
    box("sb_primary_pressed", "ROSE_700", 1.0, "ROSE_500", 1.0, 1, rad["R_SM"], px, py)
    box("sb_cash", "NIGHT_700", 1.0, "GOLD_500", 1.0, 1, rad["R_SM"], px, py)
    box("sb_edit", "NIGHT_900", 1.0, "GOLD_700", al["HAIR_A"], 1, rad["R_XS"], sp["S2"], sp["S1"])
    box("sb_track", "NIGHT_600", 1.0, None, 1.0, 0, rad["R_PILL"])
    box("sb_fill", "JADE_300", 1.0, None, 1.0, 0, rad["R_PILL"])

    R: list[str] = []
    a = R.append
    a(f'[gd_resource type="Theme" load_steps={len(subs) + 1} format=3]')
    a("")
    for sid, props in subs:
        a(f'[sub_resource type="StyleBoxFlat" id="{sid}"]')
        R.extend(props)
        a("")
    a("[resource]")
    a("metadata/generated_by = \"tools/gen_tokens.py (from tokens.json) - DO NOT EDIT\"")
    a(f"default_font_size = {ty['TYPE_BODY']}")
    col = lambda k: rgba(c[k])  # noqa: E731
    base = [
        ("Label/colors/font_color", col("PAPER_100")),
        ("Label/colors/font_shadow_color", rgba(c["SHADOW"], al["SHADOW_A"])),
        ("Label/font_sizes/font_size", str(ty["TYPE_BODY"])),
        ("Panel/styles/panel", 'SubResource("sb_plate")'),
        ("PanelContainer/styles/panel", 'SubResource("sb_plate")'),
        ("PopupPanel/styles/panel", 'SubResource("sb_sheet")'),
        ("Button/colors/font_color", col("PAPER_100")),
        ("Button/colors/font_hover_color", col("GOLD_300")),
        ("Button/colors/font_pressed_color", col("GOLD_300")),
        ("Button/colors/font_focus_color", col("PAPER_100")),
        ("Button/colors/font_disabled_color", col("PAPER_700")),
        ("Button/font_sizes/font_size", str(ty["TYPE_BODY"])),
        ("Button/styles/normal", 'SubResource("sb_btn")'),
        ("Button/styles/hover", 'SubResource("sb_btn_hover")'),
        ("Button/styles/pressed", 'SubResource("sb_btn_pressed")'),
        ("Button/styles/disabled", 'SubResource("sb_btn_disabled")'),
        ("Button/styles/focus", 'SubResource("sb_focus")'),
        ("LineEdit/colors/font_color", col("PAPER_100")),
        ("LineEdit/colors/font_placeholder_color", col("PAPER_500")),
        ("LineEdit/colors/caret_color", col("GOLD_300")),
        ("LineEdit/font_sizes/font_size", str(ty["TYPE_BODY"])),
        ("LineEdit/styles/normal", 'SubResource("sb_edit")'),
        ("LineEdit/styles/focus", 'SubResource("sb_focus")'),
        ("ProgressBar/colors/font_color", col("PAPER_100")),
        ("ProgressBar/styles/background", 'SubResource("sb_track")'),
        ("ProgressBar/styles/fill", 'SubResource("sb_fill")'),
    ]
    variations: list[tuple[str, str, list[tuple[str, str]]]] = []
    for name, key in (("LabelDisplay", "TYPE_DISPLAY"), ("LabelH1", "TYPE_H1"), ("LabelH2", "TYPE_H2"),
                      ("LabelBody", "TYPE_BODY"), ("LabelCaption", "TYPE_CAPTION")):
        variations.append((name, "Label", [("font_sizes/font_size", str(ty[key]))]))
    variations.append(("LabelCaption", "Label", [("font_sizes/font_size", str(ty["TYPE_CAPTION"])),
                                                 ("colors/font_color", col("PAPER_300"))]))
    variations.append(("LabelSubtitle", "Label", [("font_sizes/font_size", str(tok["type"]["TYPE_SUBTITLE"])),
                                                  ("colors/font_color", col("PAPER_100"))]))
    variations.append(("LabelGold", "Label", [("colors/font_color", col("GOLD_300"))]))
    variations.append(("ButtonPrimary", "Button", [
        ("colors/font_color", col("NIGHT_900")), ("colors/font_hover_color", col("NIGHT_900")),
        ("colors/font_pressed_color", col("PAPER_100")),
        ("styles/normal", 'SubResource("sb_primary")'), ("styles/hover", 'SubResource("sb_primary_hover")'),
        ("styles/pressed", 'SubResource("sb_primary_pressed")')]))
    variations.append(("ButtonCash", "Button", [
        ("colors/font_color", col("GOLD_300")), ("styles/normal", 'SubResource("sb_cash")')]))
    seen: dict[str, int] = {}
    entries: list[tuple[str, str]] = list(base)
    merged: dict[str, tuple[str, list[tuple[str, str]]]] = {}
    for name, bt, props in variations:
        if name in merged:  # later definition of the same variation overrides/extends (LabelCaption)
            merged[name] = (bt, merged[name][1] + props)
        else:
            merged[name] = (bt, list(props))
    for name in sorted(merged):
        bt, props = merged[name]
        entries.append((f"{name}/base_type", f'&"{bt}"'))
        d: dict[str, str] = {}
        for k, v in props:
            d[k] = v
        for k in sorted(d):
            entries.append((f"{name}/{k}", d[k]))
    for k, v in entries:
        seen[k] = seen.get(k, 0) + 1
        a(f"{k} = {v}")
    a("")
    return "\n".join(R)


def outputs() -> tuple[str, str, str]:
    tok = load()
    errs = validate(tok)
    if errs:
        raise SystemExit("tokens.json invalid:\n  " + "\n  ".join(errs))
    return dump_tokens(tok), build_gd(tok), build_theme(tok)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if tokens.json / outputs are stale")
    args = ap.parse_args()
    tok_txt, gd_txt, theme_txt = outputs()
    targets = [(TOKENS, tok_txt), (OUT_GD, gd_txt), (OUT_THEME, theme_txt)]
    if args.check:
        stale = [p.relative_to(REPO).as_posix() for p, t in targets
                 if not p.exists() or p.read_bytes() != t.encode("utf-8")]
        if stale:
            print("gen_tokens --check: STALE: " + ", ".join(stale))
            return 1
        print("gen_tokens --check: OK (tokens.json, tw_tokens.gd, tw_theme.tres up to date)")
        return 0
    for p, t in targets:
        p.write_bytes(t.encode("utf-8"))  # LF endings regardless of platform
        print(f"wrote {p.relative_to(REPO).as_posix()} ({len(t.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
